export function getElementBySymbol(symbol: string): ChemicalElement | undefined {
  if (!symbol) return undefined;
  return PERIODIC_TABLE.find(e => e.symbol.toLowerCase() === symbol.toLowerCase());
}

export function getElementByAtomicNumber(num: number): ChemicalElement | undefined {
  return PERIODIC_TABLE.find(e => e.atomicNumber === num);
}

